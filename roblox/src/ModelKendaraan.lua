	end
	b(Vector3.new(1.375, 1.5, 0.75), H * CFrame.new(0, 0.75, 0), o.baju)
	for _, x in ipairs({ -0.99, 0.99 }) do
		b(Vector3.new(0.56, 1.31, 0.6), H * CFrame.new(x, 1.375, 0) * CFrame.Angles(tangan, 0, 0) * CFrame.new(0, -0.62, 0), o.baju)
